SELECT C.ITEM_ID, C.ITEM_NAME, C.RARITY
FROM (ITEM_INFO AS C NATURAL JOIN ITEM_TREE AS T)
JOIN ITEM_INFO AS P ON T.PARENT_ITEM_ID = P.ITEM_ID
WHERE P.RARITY = 'RARE'
ORDER BY C.ITEM_ID DESC

