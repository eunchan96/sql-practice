SELECT CONCAT((MONTH(DIFFERENTIATION_DATE) - 1) DIV 3 + 1, 'Q') AS QUATER,
    COUNT(*) AS ECOLI_COUNT
FROM ECOLI_DATA
GROUP BY (MONTH(DIFFERENTIATION_DATE) - 1) DIV 3
ORDER BY QUATER

---
SELECT CONCAT(QUARTER(DIFFERENTIATION_DATE), 'Q') AS QUARTER,
       COUNT(*) AS ECOLI_COUNT
FROM ECOLI_DATA
GROUP BY QUARTER(DIFFERENTIATION_DATE)
ORDER BY QUARTER(DIFFERENTIATION_DATE);